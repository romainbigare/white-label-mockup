/** A crop's picture, or the generic sprout or tree when it has none. */
export function cropIcon(cropId, { trees = false, size = 28 } = {}) {
  const inner = CROP_GLYPHS[cropId];
  return inner
    ? glyph(inner, size, { strokeWidth: 1.6, extraClass: 'ico--crop' })
    : glyph(null, size, { name: trees ? 'tree' : 'sprout', strokeWidth: 1.6, extraClass: 'ico--crop' });
}
