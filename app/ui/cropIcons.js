/* ---------------------------------------------------------------------------
   cropIcons.js — one small picture per crop and tree species (v1.7.4).

   B1's plot cards say what grows in a field with a picture as well as a word,
   so a farmer scanning twelve cards finds his tomatoes by their shape before
   he reads. Lucide carries a handful of these (wheat, carrot, apple, grape)
   and nothing for sorghum, okra, alfalfa or a date palm, so the set is drawn
   here, once, on Lucide's own grid so it sits beside the app's other glyphs:
   24 × 24, round caps and joins, outline only, no fill — but a lighter
   stroke (1.6 against 2), because these are pictures of things rather than
   controls, and at 30 px a heavier line turns a grape bunch into a blot.

   KEYED BY CROP ID, the ids content.json gives the 37 crops: 25 grown in
   fields, 12 on trees. A crop with no drawing falls back to the sprout or the
   tree the app used before. Each is meant to be told apart from the others
   at a glance, not to be botanically right: the lime is a cut slice so it is
   not the orange, the guava is cut open so it is not the apple.
   --------------------------------------------------------------------------- */

