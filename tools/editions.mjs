/* Write expo/index.html — the exhibition edition's page — from index.html.

   The two pages are the same page: the same harness, the same modules, the same
   stylesheets. The copy differs in three things only:
     * its stylesheet, module and manifest links point one folder up, at the
       one copy of app/ and the one manifest — so installing from either page
       installs the exhibition edition (what the app builds at run time goes
       through app/core/site.js);
     * data-edition="expo" on <html>, which is all app/core/edition.js reads;
     * its title.
   So the page is generated rather than kept by hand, and tools/syntax.sh fails
   the deploy when the committed copy is out of date.

   Usage:  node tools/editions.mjs           write expo/index.html
           node tools/editions.mjs --check   exit 1 if it is out of date
*/
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, 'expo/index.html');

function replaceOnce(text, from, to) {
  const at = text.indexOf(from);
  if (at < 0 || text.indexOf(from, at + 1) >= 0) throw new Error(`index.html: expected exactly one ${JSON.stringify(from)}`);
  return text.slice(0, at) + to + text.slice(at + from.length);
}

const source = await readFile(resolve(ROOT, 'index.html'), 'utf8');
let page = source;
page = replaceOnce(page, '<!doctype html>\n',
  '<!doctype html>\n<!-- GENERATED by tools/editions.mjs from index.html — edit that file and re-run it. -->\n');
page = replaceOnce(page, '<html lang="en">', '<html lang="en" data-edition="expo">');
page = page.replace(/(href|src)="app\//g, '$1="../app/');
page = replaceOnce(page, 'href="manifest.webmanifest"', 'href="../manifest.webmanifest"');
page = page.replace(/<title>[^<]*<\/title>/, '<title>Wafra Farm</title>');

if (process.argv.includes('--check')) {
  const current = await readFile(OUT, 'utf8').catch(() => '');
  if (current !== page) {
    console.log('=== expo/index.html is out of date: run node tools/editions.mjs');
    process.exit(1);
  }
} else {
  await mkdir(resolve(ROOT, 'expo'), { recursive: true });
  await writeFile(OUT, page);
  console.log('wrote expo/index.html');
}
